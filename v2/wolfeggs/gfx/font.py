GLYPHS: dict[str, list[str]] = {ch: rows.split() for ch, rows in _RAW.items()}
for _a, _b in _ALIASES.items():
    GLYPHS[_a] = GLYPHS[_b]


class PixelFont:
    def __init__(self, scale: int = 1):
        self.scale = scale
        self._cache: dict[tuple, pygame.Surface] = {}

    def has_glyph(self, ch: str) -> bool:
        return ch == " " or ch.upper() in GLYPHS

    def size(self, text: str) -> tuple[int, int]:
        n = len(text)
        w = n * (GW + 1) - 1 if n else 0
        return w * self.scale, GH * self.scale

    def _draw(self, surf: pygame.Surface, text: str, color, ox: int, oy: int) -> None:
        s = self.scale
        for i, ch in enumerate(text.upper()):
            rows = GLYPHS.get(ch) if ch != " " else None
            if ch != " " and rows is None:
                rows = GLYPHS["?"]
            if rows is None:
                continue
            x0 = ox + i * (GW + 1) * s
            for y, row in enumerate(rows):
                for x, bit in enumerate(row):
                    if bit == "1":
                        surf.fill(color, (x0 + x * s, oy + y * s, s, s))

    def render(self, text: str, color, shadow=None) -> pygame.Surface:
        key = (text, tuple(color), tuple(shadow) if shadow else None)
        cached = self._cache.get(key)
        if cached is not None:
            return cached
        w, h = self.size(text)
        pad = self.scale if shadow else 0
        surf = pygame.Surface((max(1, w + pad), h + pad), pygame.SRCALPHA)
        if shadow:
            self._draw(surf, text, shadow, pad, pad)
        self._draw(surf, text, color, 0, 0)
        if len(self._cache) > 512:
            self._cache.clear()
        self._cache[key] = surf
        return surf
